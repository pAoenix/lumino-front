            method: "GET",
            success: (res) => {
              if (res.data?.message && res.data?.message) {
                uni.showToast({
                  title: "用户不存在",
                  icon: "none",
                });
                reject("用户不存在");
              } else {
                uni.setStorageSync("token", res.data.phone_number);
                uni.setStorageSync("userInfo", JSON.stringify(res.data));
                uni.setStorageSync("userName", res.data.name);
                uni.setStorageSync("phone_number", res.data.phone_number);
                if (res.data?.friend?.length) {
                  // 使用 map 生成所有请求 Promise
                  const promiseList = res.data.friend.map((id) =>
                    this.getUserData(id)
                  );
                  // 使用 Promise.all 等待所有请求完成
                  Promise.all(promiseList)
                    .then((results) => {
                      this.globalData.userList = results;
                      resolve(results);
                    })
                    .catch((err) => {
                      this.globalData.userList = [];
                      resolve([]);
                    });
                } else {
                  reject();
                }
              }
            },
            fail: (err) => {
              reject(err);
            },
          });
        } else {
          reject("请登录");
        }
      });
